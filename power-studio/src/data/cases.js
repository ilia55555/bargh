function attachDyn(cs) {
  const d = DYN[cs.name];
  cs.gen.forEach((g, i) => {
    g.H = d ? d.H[i] : 5 * (g.Pmax || 100) / cs.baseMVA;
    g.xdp = d ? d.xdp[i] : 0.25 * cs.baseMVA / Math.max(g.Pmax || 100, 1);
    g.D = 0;
    g.FOR = 0.04;
  });
  cs.description = DESC[cs.name] || cs.name;
  return cs;
}
export function prepareCase(cs) { return attachDyn(cs); }

export const CASES = {
  case9: () => attachDyn(fromMatpower(case9mpc)),
  case14: () => attachDyn(fromMatpower(case14mpc, { freq: 60 })),
  case39: () => attachDyn(fromMatpower(case39mpc)),
  case33bw: () => attachDyn(fromMatpower(case33mpc(), { freq: 50, radial: true })),
};
export const CASE_LIST = Object.keys(CASES).map((k) => ({ key: k, label: DESC[k] }));
export const loadCase = (k) => CASES[k]();
